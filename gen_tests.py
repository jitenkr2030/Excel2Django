"""Generate tests for models, views, API."""
from helpers import put

def generate_tests(report, root, A):
    names = [i["model"] for i in report]
    L = []
    L.append("from django.test import TestCase, Client")
    L.append("from django.urls import reverse")
    L.append("from rest_framework.test import APIClient")
    L.append("from rest_framework.authtoken.models import Token")
    L.append("from .models import User")
    if names:
        L.append("from .models import " + ", ".join(names))
    L.append("")
    L.append("")
    L.append("class BaseModelTest(TestCase):")
    L.append("    def setUp(self):")
    L.append("        self.client = Client()")
    L.append("        self.api = APIClient()")
    L.append("        self.admin = User.objects.create_superuser('admin', 'admin@test.com', 'pass12345')")
    L.append("        self.creator = User.objects.create_user('creator', 'creator@test.com', 'pass12345')")
    L.append("        self.creator.role = 'creator'")
    L.append("        self.creator.save()")
    L.append("        self.client_user = User.objects.create_user('client', 'client@test.com', 'pass12345')")
    L.append("        self.client_user.role = 'client'")
    L.append("        self.client_user.save()")
    L.append("        self.token = Token.objects.create(user=self.admin)")
    L.append("        self.api.credentials(HTTP_AUTHORIZATION='Token ' + self.token.key)")
    L.append("")
    L.append("")
    L.append("class AuthTests(BaseModelTest):")
    L.append("    def test_login_page(self):")
    L.append("        r = self.client.get('/auth/login/')")
    L.append("        self.assertEqual(r.status_code, 200)")
    L.append("")
    L.append("    def test_register_page(self):")
    L.append("        r = self.client.get('/auth/register/')")
    L.append("        self.assertEqual(r.status_code, 200)")
    L.append("")
    L.append("    def test_login_success(self):")
    L.append("        r = self.client.post('/auth/login/', {'username': 'admin', 'password': 'pass12345'})")
    L.append("        self.assertEqual(r.status_code, 302)")
    L.append("")
    L.append("    def test_login_fail(self):")
    L.append("        r = self.client.post('/auth/login/', {'username': 'admin', 'password': 'wrong'})")
    L.append("        self.assertEqual(r.status_code, 200)")
    L.append("")
    L.append("    def test_register_new_user(self):")
    L.append("        r = self.client.post('/auth/register/', {")
    L.append("            'username': 'newuser', 'email': 'new@test.com',")
    L.append("            'first_name': 'New', 'last_name': 'User',")
    L.append("            'role': 'client',")
    L.append("            'password1': 'StrongPass123!', 'password2': 'StrongPass123!'")
    L.append("        })")
    L.append("        self.assertEqual(r.status_code, 302)")
    L.append("        self.assertTrue(User.objects.filter(username='newuser').exists())")
    L.append("")
    L.append("    def test_dashboard_requires_login(self):")
    L.append("        r = self.client.get('/dashboard/')")
    L.append("        self.assertEqual(r.status_code, 302)")
    L.append("")
    L.append("    def test_dashboard_admin(self):")
    L.append("        self.client.login(username='admin', password='pass12345')")
    L.append("        r = self.client.get('/dashboard/')")
    L.append("        self.assertEqual(r.status_code, 200)")
    L.append("")
    L.append("    def test_profile_view(self):")
    L.append("        self.client.login(username='admin', password='pass12345')")
    L.append("        r = self.client.get('/auth/profile/')")
    L.append("        self.assertEqual(r.status_code, 200)")
    L.append("")
    L.append("    def test_password_change(self):")
    L.append("        self.client.login(username='admin', password='pass12345')")
    L.append("        r = self.client.get('/auth/password/change/')")
    L.append("        self.assertEqual(r.status_code, 200)")
    L.append("")
    L.append("")
    L.append("class PermissionTests(BaseModelTest):")
    L.append("    def test_delete_admin_only(self):")
    L.append("        self.client.login(username='client', password='pass12345')")
    L.append("        r = self.client.get('/data/users/1/delete/')")
    L.append("        self.assertEqual(r.status_code, 302)")
    L.append("")
    L.append("    def test_create_creator_allowed(self):")
    L.append("        self.client.login(username='creator', password='pass12345')")
    L.append("        r = self.client.get('/data/users/create/')")
    L.append("        self.assertEqual(r.status_code, 200)")
    L.append("")
    L.append("    def test_create_client_blocked(self):")
    L.append("        self.client.login(username='client', password='pass12345')")
    L.append("        r = self.client.get('/data/users/create/')")
    L.append("        self.assertEqual(r.status_code, 302)")
    L.append("")
    L.append("")
    L.append("class ApiTests(BaseModelTest):")
    L.append("    def test_api_list(self):")
    L.append("        r = self.api.get('/api/users/')")
    L.append("        self.assertEqual(r.status_code, 200)")
    L.append("")
    L.append("    def test_api_token_auth(self):")
    L.append("        r = self.client.post('/api/auth/token/', {'username': 'admin', 'password': 'pass12345'})")
    L.append("        self.assertEqual(r.status_code, 200)")
    L.append("        self.assertIn('token', r.json())")
    L.append("")
    L.append("    def test_api_unauthenticated(self):")
    L.append("        api = APIClient()")
    L.append("        r = api.get('/api/users/')")
    L.append("        self.assertEqual(r.status_code, 401)")
    L.append("")
    L.append("    def test_api_register(self):")
    L.append("        api = APIClient()")
    L.append("        r = api.post('/api/register/', {")
    L.append("            'username': 'apiuser', 'email': 'api@test.com',")
    L.append("            'first_name': 'Api', 'last_name': 'User',")
    L.append("            'role': 'client', 'password': 'StrongPass123!'")
    L.append("        })")
    L.append("        self.assertEqual(r.status_code, 201)")
    L.append("")
    L.append("")
    L.append("class PageTests(BaseModelTest):")
    L.append("    def test_landing(self):")
    L.append("        r = self.client.get('/')")
    L.append("        self.assertEqual(r.status_code, 200)")
    L.append("")
    L.append("    def test_about(self):")
    L.append("        r = self.client.get('/about/')")
    L.append("        self.assertEqual(r.status_code, 200)")
    L.append("")
    L.append("    def test_contact(self):")
    L.append("        r = self.client.get('/contact/')")
    L.append("        self.assertEqual(r.status_code, 200)")
    L.append("")
    L.append("    def test_faq(self):")
    L.append("        r = self.client.get('/faq/')")
    L.append("        self.assertEqual(r.status_code, 200)")
    L.append("")
    L.append("")

    for n in names[:5]:
        L.append("")
        L.append(f"class {n}ModelTest(BaseModelTest):")
        L.append(f"    def test_{n.lower()}_list(self):")
        L.append("        self.client.login(username='admin', password='pass12345')")
        L.append(f"        r = self.client.get('/data/{n.lower()}/')")
        L.append("        self.assertEqual(r.status_code, 200)")
        L.append("")
        L.append(f"    def test_{n.lower()}_api(self):")
        L.append(f"        r = self.api.get('/api/{n.lower()}/')")
        L.append("        self.assertEqual(r.status_code, 200)")
        L.append("")

    put(root, f"{A}/tests.py", "\n".join(L))
    print(f"  Tests: Auth, Permissions, API, Pages, {min(5, len(names))} model tests")
