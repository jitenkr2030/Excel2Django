"""Generate views.py and urls.py with role-based access."""
from helpers import put

def generate_views(report, root, A):
    names = [i["model"] for i in report]
    L = []
    L.append("from django.shortcuts import render, redirect, get_object_or_404")
    L.append("from django.contrib.auth import login, logout, authenticate")
    L.append("from django.contrib import messages")
    L.append("from django.core.paginator import Paginator")
    L.append("from django.db.models import Q")
    L.append("from .models import User")
    if names:
        L.append("from .models import " + ", ".join(names))
    L.append("from .forms import RegisterForm, ProfileForm")
    if names:
        L.append("from .forms import " + ", ".join(n + "Form" for n in names))
    L.append("from .permissions import admin_required, creator_required, login_required_page")
    L.append("")
    L.append("")
    L.append("def get_sidebar_stats():")
    L.append("    stats = []")
    for n in names:
        L.append(f"    stats.append({{'name': '{n}', 'count': {n}.objects.count(), 'url': '/data/{n.lower()}/'}})")
    L.append("    return stats")
    L.append("")
    L.append("")
    L.append("def index(request):")
    L.append("    return render(request, 'portal/index.html', {'title': 'Home'})")
    L.append("")
    L.append("")
    L.append("def login_view(request):")
    L.append("    if request.user.is_authenticated:")
    L.append("        return redirect('dashboard')")
    L.append("    if request.method == 'POST':")
    L.append("        user = authenticate(request, username=request.POST.get('username',''), password=request.POST.get('password',''))")
    L.append("        if user:")
    L.append("            login(request, user)")
    L.append("            messages.success(request, f'Welcome back, {user.username}!')")
    L.append("            return redirect('dashboard')")
    L.append("        messages.error(request, 'Invalid username or password.')")
    L.append("    return render(request, 'portal/login.html', {'title': 'Sign In'})")
    L.append("")
    L.append("")
    L.append("def register_view(request):")
    L.append("    if request.user.is_authenticated:")
    L.append("        return redirect('dashboard')")
    L.append("    if request.method == 'POST':")
    L.append("        form = RegisterForm(request.POST)")
    L.append("        if form.is_valid():")
    L.append("            user = form.save(commit=False)")
    L.append("            user.role = form.cleaned_data.get('role', 'client')")
    L.append("            user.save()")
    L.append("            messages.success(request, 'Account created! Please sign in.')")
    L.append("            return redirect('login')")
    L.append("        return render(request, 'portal/register.html', {'title': 'Register', 'form': form})")
    L.append("    return render(request, 'portal/register.html', {'title': 'Register', 'form': RegisterForm()})")
    L.append("")
    L.append("")
    L.append("def logout_view(request):")
    L.append("    logout(request)")
    L.append("    return redirect('index')")
    L.append("")
    L.append("")
    L.append("@login_required_page")
    L.append("def dashboard(request):")
    L.append("    tpl = {'admin': 'portal/dashboard.html', 'creator': 'portal/creator_dashboard.html', 'client': 'portal/client_dashboard.html'}")
    L.append("    t = tpl.get(request.user.role, 'portal/client_dashboard.html')")
    L.append("    return render(request, t, {'title': 'Dashboard', 'stats': get_sidebar_stats()})")
    L.append("")
    L.append("")
    L.append("@login_required_page")
    L.append("def profile_view(request):")
    L.append("    if request.method == 'POST':")
    L.append("        form = ProfileForm(request.POST, instance=request.user)")
    L.append("        if form.is_valid():")
    L.append("            form.save()")
    L.append("            messages.success(request, 'Profile updated!')")
    L.append("            return redirect('profile')")
    L.append("        return render(request, 'portal/profile.html', {'title': 'My Profile', 'form': form})")
    L.append("    return render(request, 'portal/profile.html', {'title': 'My Profile', 'form': ProfileForm(instance=request.user)})")
    L.append("")
    L.append("")
    L.append("@login_required_page")
    L.append("def password_change(request):")
    L.append("    from django.contrib.auth.forms import PasswordChangeForm")
    L.append("    from django.contrib.auth import update_session_auth_hash")
    L.append("    if request.method == 'POST':")
    L.append("        form = PasswordChangeForm(request.user, request.POST)")
    L.append("        if form.is_valid():")
    L.append("            user = form.save()")
    L.append("            update_session_auth_hash(request, user)")
    L.append("            messages.success(request, 'Password changed successfully!')")
    L.append("            return redirect('profile')")
    L.append("        return render(request, 'portal/password_change.html', {'title': 'Change Password', 'form': form})")
    L.append("    return render(request, 'portal/password_change.html', {'title': 'Change Password', 'form': PasswordChangeForm(request.user)})")
    L.append("")
    L.append("")
    L.append("def password_reset(request):")
    L.append("    if request.method == 'POST':")
    L.append("        email = request.POST.get('email', '')")
    L.append("        if User.objects.filter(email__iexact=email).exists():")
    L.append("            messages.success(request, f'Password reset link sent to {email}')")
    L.append("        else:")
    L.append("            messages.error(request, 'No account found with that email.')")
    L.append("        return redirect('password_reset')")
    L.append("    return render(request, 'portal/password_reset.html', {'title': 'Reset Password'})")
    L.append("")
    L.append("")
    L.append("@login_required_page")
    L.append("def notification_list(request):")
    L.append("    from django.apps import apps")
    L.append("    try:")
    L.append("        model = apps.get_model('portal', 'Notifications')")
    L.append("        items = model.objects.all()[:50]")
    L.append("    except LookupError:")
    L.append("        items = []")
    L.append("    return render(request, 'portal/notifications.html', {'title': 'Notifications', 'items': items, 'stats': get_sidebar_stats()})")
    L.append("")
    L.append("")
    L.append("@login_required_page")
    L.append("def model_list(request, model_name):")
    L.append("    model = _get_model(request, model_name)")
    L.append("    if isinstance(model, dict): return model")
    L.append("    fields = [f for f in model._meta.fields if f.name != 'id']")
    L.append("    q = request.GET.get('q', '')")
    L.append("    qs = model.objects.all()")
    L.append("    if q:")
    L.append("        qf = Q()")
    L.append("        for f in fields[:5]:")
    L.append("            qf |= Q(**{f.name + '__icontains': q})")
    L.append("        qs = qs.filter(qf)")
    L.append("    page = Paginator(qs, 20).get_page(request.GET.get('page', 1))")
    L.append("    can_create = request.user.is_admin_role or request.user.is_creator_role")
    L.append("    return render(request, 'portal/records.html', {'title': model.__name__, 'model_name': model_name.lower(), 'fields': fields, 'page': page, 'search': q, 'can_create': can_create, 'stats': get_sidebar_stats()})")
    L.append("")
    L.append("")
    L.append("@login_required_page")
    L.append("def model_detail(request, model_name, pk):")
    L.append("    model = _get_model(request, model_name)")
    L.append("    if isinstance(model, dict): return model")
    L.append("    obj = get_object_or_404(model, pk=pk)")
    L.append("    fields = [f for f in model._meta.fields if f.name != 'id']")
    L.append("    return render(request, 'portal/detail.html', {'title': model.__name__, 'model_name': model_name.lower(), 'obj': obj, 'fields': fields, 'stats': get_sidebar_stats()})")
    L.append("")
    L.append("")
    L.append("@creator_required")
    L.append("def model_create(request, model_name):")
    L.append("    model = _get_model(request, model_name)")
    L.append("    if isinstance(model, dict): return model")
    L.append("    FormClass = _get_form(model_name)")
    L.append("    if request.method == 'POST':")
    L.append("        form = FormClass(request.POST)")
    L.append("        if form.is_valid():")
    L.append("            form.save()")
    L.append("            messages.success(request, 'Record created!')")
    L.append("            return redirect('model_list', model_name=model_name.lower())")
    L.append("    else:")
    L.append("        form = FormClass()")
    L.append("    return render(request, 'portal/form.html', {'title': f'Create {model.__name__}', 'model_name': model_name.lower(), 'form': form, 'action': 'Create', 'stats': get_sidebar_stats()})")
    L.append("")
    L.append("")
    L.append("@creator_required")
    L.append("def model_edit(request, model_name, pk):")
    L.append("    model = _get_model(request, model_name)")
    L.append("    if isinstance(model, dict): return model")
    L.append("    obj = get_object_or_404(model, pk=pk)")
    L.append("    FormClass = _get_form(model_name)")
    L.append("    if request.method == 'POST':")
    L.append("        form = FormClass(request.POST, instance=obj)")
    L.append("        if form.is_valid():")
    L.append("            form.save()")
    L.append("            messages.success(request, 'Record updated!')")
    L.append("            return redirect('model_detail', model_name=model_name.lower(), pk=pk)")
    L.append("    else:")
    L.append("        form = FormClass(instance=obj)")
    L.append("    return render(request, 'portal/form.html', {'title': f'Edit {model.__name__}', 'model_name': model_name.lower(), 'form': form, 'action': 'Save', 'stats': get_sidebar_stats()})")
    L.append("")
    L.append("")
    L.append("@admin_required")
    L.append("def model_delete(request, model_name, pk):")
    L.append("    model = _get_model(request, model_name)")
    L.append("    if isinstance(model, dict): return model")
    L.append("    obj = get_object_or_404(model, pk=pk)")
    L.append("    if request.method == 'POST':")
    L.append("        obj.delete()")
    L.append("        messages.success(request, 'Record deleted!')")
    L.append("        return redirect('model_list', model_name=model_name.lower())")
    L.append("    return render(request, 'portal/confirm_delete.html', {'title': f'Delete {model.__name__}', 'model_name': model_name.lower(), 'obj': obj, 'stats': get_sidebar_stats()})")
    L.append("")
    L.append("")
    L.append("def _get_model(request, name):")
    L.append("    from django.apps import apps")
    L.append("    try:")
    L.append("        return apps.get_model('portal', name)")
    L.append("    except LookupError:")
    L.append("        messages.error(request, f'Model {name} not found.')")
    L.append("        return redirect('dashboard')")
    L.append("")
    L.append("")
    L.append("def _get_form(name):")
    L.append("    from django.apps import apps")
    L.append("    from . import forms as forms_mod")
    L.append("    cls_name = apps.get_model('portal', name).__name__")
    L.append("    return getattr(forms_mod, cls_name + 'Form')")
    put(root, f"{A}/views.py", "\n".join(L))

def generate_urls(root, A):
    put(root, f"{A}/urls.py", URL_CODE)

URL_CODE = """from django.urls import path
from . import views

urlpatterns = [
    path('', views.index, name='index'),
    path('auth/login/', views.login_view, name='login'),
    path('auth/register/', views.register_view, name='register'),
    path('auth/logout/', views.logout_view, name='logout'),
    path('auth/profile/', views.profile_view, name='profile'),
    path('auth/password/change/', views.password_change, name='password_change'),
    path('auth/password/reset/', views.password_reset, name='password_reset'),
    path('dashboard/', views.dashboard, name='dashboard'),
    path('notifications/', views.notification_list, name='notifications'),
    path('data/<str:model_name>/', views.model_list, name='model_list'),
    path('data/<str:model_name>/create/', views.model_create, name='model_create'),
    path('data/<str:model_name>/<int:pk>/', views.model_detail, name='model_detail'),
    path('data/<str:model_name>/<int:pk>/edit/', views.model_edit, name='model_edit'),
    path('data/<str:model_name>/<int:pk>/delete/', views.model_delete, name='model_delete'),
]
"""
